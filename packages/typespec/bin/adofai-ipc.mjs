#!/usr/bin/env node
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compile, NodeHost, formatDiagnostic } from "@typespec/compiler";
import { renderContract } from "../src/generate.js";

export async function generate(configFile, check = false) {
  const configPath = path.resolve(configFile), base = path.dirname(configPath);
  const config = JSON.parse(await fs.readFile(configPath, "utf8"));
  if (typeof config.contract !== "string" || typeof config.typescript?.output !== "string" || typeof config.csharp?.output !== "string")
    throw new Error("Set contract, typescript.output and csharp.output in the IPC generator config.");
  const program = await compile(NodeHost, path.resolve(base, config.contract), { noEmit: true });
  if (program.hasError()) throw new Error(program.diagnostics.map(d => formatDiagnostic(d)).join("\n"));
  const output = renderContract(program, { packageName: config.typescript.packageName, csharpNamespace: config.csharp.namespace, workspace: config.typescript.workspace,
    packageVersion: config.typescript.version, packagePrivate: config.typescript.private, runtimeDependency: config.typescript.runtimeDependency });
  const changes = [], plans = [];
  const marker = ".adofai-ipc.generated.json";
  for (const language of ["typescript", "csharp"]) {
    const directory = path.resolve(base, config[language].output);
    if (language === "typescript") {
      try {
        const existing = JSON.parse(await fs.readFile(path.join(directory, "package.json"), "utf8"));
        if (existing.adofaiIpcGenerated !== true) throw new Error(`Refusing to replace a non-generated package: ${directory}`);
      } catch (error) { if (error.code !== "ENOENT") throw error; }
    }
    let previous = [];
    try {
      const manifest = JSON.parse(await fs.readFile(path.join(directory, marker), "utf8"));
      if (manifest.generator !== "@adofai-ipc/typespec" || !Array.isArray(manifest.files) ||
        manifest.files.some(file => typeof file !== "string" || path.basename(file) !== file || file === marker))
        throw new Error(`Invalid IPC generation manifest: ${directory}`);
      previous = manifest.files;
    } catch (error) { if (error.code !== "ENOENT") throw error; }
    const files = { ...output[language], [marker]: JSON.stringify({ generator: "@adofai-ipc/typespec", files: Object.keys(output[language]).sort() }, null, 2) + "\n" };
    for (const [file, content] of Object.entries(files)) {
      const destination = path.join(directory, file);
      let current;
      try { current = await fs.readFile(destination, "utf8"); } catch (error) { if (error.code !== "ENOENT") throw error; }
      if (current === content) continue;
      if (current !== undefined && file !== marker && file !== "package.json" && !previous.includes(file) && !current.startsWith("// Generated by @adofai-ipc/typespec."))
        throw new Error(`Refusing to replace a non-generated source file: ${destination}`);
      changes.push(destination);
      plans.push({ directory, destination, content });
    }
    for (const file of previous) if (!Object.hasOwn(files, file)) {
      const destination = path.join(directory, file);
      try { await fs.access(destination); } catch (error) { if (error.code === "ENOENT") continue; throw error; }
      changes.push(destination); plans.push({ destination });
    }
  }
  if (check && changes.length) throw new Error("Generated IPC files are out of date:\n" + changes.join("\n"));
  if (!check) for (const plan of plans) {
    if (plan.content === undefined) await fs.unlink(plan.destination);
    else { await fs.mkdir(plan.directory, { recursive: true }); await fs.writeFile(plan.destination, plan.content); }
  }
  return { id: output.contract.id, hash: output.contract.hash, changes };
}

const entry = process.argv[1] ? await fs.realpath(path.resolve(process.argv[1])).catch(() => undefined) : undefined;
if (entry === fileURLToPath(import.meta.url)) {
  try {
    const args = process.argv.slice(2);
    if (args[0] !== "generate" || args.includes("--help")) {
      console.log("Usage: adofai-ipc generate [--config adofai-ipc.config.json] [--check]");
      if (args[0] !== "generate" && args.length && !args.includes("--help")) process.exitCode = 1;
    } else {
      const index = args.indexOf("--config");
      if (index !== -1 && !args[index + 1]) throw new Error("--config requires a path.");
      const known = args.filter((_, i) => i !== 0 && i !== index && i !== index + 1);
      if (known.some(value => value !== "--check")) throw new Error("Unknown generator option.");
      const result = await generate(index === -1 ? "adofai-ipc.config.json" : args[index + 1], args.includes("--check"));
      console.log(`IPC ${result.id}: ${result.changes.length} file(s) ${args.includes("--check") ? "need updating" : "updated"}.`);
    }
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
