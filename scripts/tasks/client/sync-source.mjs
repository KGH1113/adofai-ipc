import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve, join } from "node:path";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const destination = process.argv[2];
if (!destination) throw new Error("Usage: ./scripts/run.sh client-sync <vendor-directory>");
const target = resolve(destination);
const source = join(root, "packages/client/src");
const files = readdirSync(source).filter(name => name.endsWith(".ts")).sort();
const hashes = {};
mkdirSync(join(target, "src"), { recursive: true });
for (const name of files) {
  const content = readFileSync(join(source, name));
  writeFileSync(join(target, "src", name), content);
  hashes[name] = createHash("sha256").update(content).digest("hex");
}
const revision = execFileSync("git", ["rev-parse", "HEAD"], { cwd: root, encoding: "utf8" }).trim();
const dirty = execFileSync("git", ["status", "--porcelain", "--", "packages/client/src"], { cwd: root, encoding: "utf8" }).trim().length > 0;
const sdkVersion = readFileSync(join(source, "version.ts"), "utf8").match(/CLIENT_VERSION = "([^"]+)"/)[1];
const manifest = { source: "https://github.com/KGH1113/adofai-ipc", sourceRevision: revision, sourceDirty: dirty, version: sdkVersion, protocolVersion: 3, files: hashes };
writeFileSync(join(target, "source.json"), JSON.stringify(manifest, null, 2) + "\n");
writeFileSync(join(target, "README.md"), "# ADOFAI-IPC source snapshot\n\nGenerated by upstream `./scripts/run.sh client-sync`. Use the raw TypeScript SDK without an npm dependency. Do not edit the vendored source; change upstream and regenerate. `source.json` records provenance and SHA-256 per file.\n");
writeFileSync(join(target, "LICENSE"), readFileSync(join(root, "LICENSE")));
console.log(`Synchronized ${files.length} SDK source files to ${target} (${revision}${dirty ? ", working tree" : ""}).`);
